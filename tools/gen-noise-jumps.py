#!/usr/bin/env python3
"""Exact GF(2) LFSR jump tables for the native noise mixer."""
from pathlib import Path
import sys
root=Path(__file__).resolve().parent.parent
def advance(x,n,short=False):
    for _ in range(n):
        bit=(x^(x>>1))&1;x=(x>>1)|(bit<<14)
        if short:x=(x&~64)|(bit<<6)
    return x
lines=['; Generated by tools/gen-noise-jumps.py; values are little-endian.']
for n in [32,128]:
    for name,values in [
        (f'.Lwide{n}_lo',[advance(i,n) for i in range(256)]),
        (f'.Lwide{n}_hi',[advance(i<<8,n) for i in range(128)]),
        (f'.Lshort{n}',[advance(i,n,True) for i in range(128)])]:
        data=[byte for x in values for byte in [x&255,x>>8]]
        lines.append(name+':')
        lines.extend(' .byte '+','.join(map(str,data[i:i+16])) for i in range(0,len(data),16))
text='\n'.join(lines)+'\n';target=root/'audio/noise-jumps.inc'
if '--check' in sys.argv:assert target.read_text()==text
else:target.write_text(text)
